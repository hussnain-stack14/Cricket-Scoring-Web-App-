import { jsPDF } from 'jspdf';
import autoTable from 'jspdf-autotable';
import { buildScorecard, scorecardFilename } from './scorecard.js';

const COLORS = {
  green: [31, 90, 61],
  deep: [18, 61, 43],
  lime: [217, 239, 177],
  pale: [239, 245, 234],
  ink: [23, 43, 34],
  muted: [100, 116, 106],
  line: [220, 229, 218],
  white: [255, 255, 255],
};
const PAGE = { width: 210, height: 297, margin: 13, footer: 17 };

function writeHeader(doc, subtitle) {
  doc.setFillColor(...COLORS.green);
  doc.roundedRect(PAGE.margin, 11, 12, 12, 2, 2, 'F');
  doc.setTextColor(...COLORS.lime);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(11);
  doc.text('C', PAGE.margin + 6, 19.2, { align: 'center' });
  doc.setTextColor(...COLORS.deep);
  doc.setFontSize(16);
  doc.text('CREASE', PAGE.margin + 16, 16.5);
  doc.setTextColor(...COLORS.muted);
  doc.setFont('helvetica', 'normal');
  doc.setFontSize(8);
  doc.text('MATCH SCORECARD', PAGE.margin + 16, 21.5);
  doc.setTextColor(...COLORS.green);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(9);
  doc.text(subtitle.toUpperCase(), PAGE.width - PAGE.margin, 17, { align: 'right' });
  doc.setDrawColor(...COLORS.line);
  doc.setLineWidth(0.4);
  doc.line(PAGE.margin, 28, PAGE.width - PAGE.margin, 28);
}

function writeFooter(doc, report) {
  const pages = doc.getNumberOfPages();
  const date = new Date(`${report.date}T00:00:00`);
  const formattedDate = Number.isNaN(date.valueOf())
    ? report.date
    : new Intl.DateTimeFormat('en-GB', { dateStyle: 'medium' }).format(date);
  for (let page = 1; page <= pages; page++) {
    doc.setPage(page);
    doc.setDrawColor(...COLORS.line);
    doc.line(
      PAGE.margin,
      PAGE.height - PAGE.footer,
      PAGE.width - PAGE.margin,
      PAGE.height - PAGE.footer,
    );
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7);
    doc.setTextColor(...COLORS.muted);
    const details = [formattedDate, report.toss, report.format, 'Generated by Crease']
      .filter(Boolean)
      .join('  ·  ');
    doc.text(details, PAGE.margin, PAGE.height - 10, {
      maxWidth: PAGE.width - PAGE.margin * 2 - 23,
    });
    doc.setFont('helvetica', 'bold');
    doc.text(`${page} / ${pages}`, PAGE.width - PAGE.margin, PAGE.height - 10, {
      align: 'right',
    });
  }
}

function addSectionTitle(doc, title, y) {
  if (y > PAGE.height - PAGE.footer - 22) {
    doc.addPage();
    y = 17;
  }
  doc.setTextColor(...COLORS.deep);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text(title, PAGE.margin, y);
  return y + 3;
}

function addTable(doc, { title, headers, rows, y, numericColumns = [] }) {
  const startY = addSectionTitle(doc, title, y);
  autoTable(doc, {
    startY,
    head: [headers],
    body: rows.length ? rows : [['No recorded figures', ...Array(headers.length - 1).fill('')]],
    theme: 'grid',
    margin: { left: PAGE.margin, right: PAGE.margin, bottom: PAGE.footer + 3 },
    styles: {
      font: 'helvetica',
      fontSize: 7.5,
      cellPadding: 2,
      textColor: COLORS.ink,
      lineColor: COLORS.line,
      lineWidth: 0.15,
      overflow: 'linebreak',
      valign: 'middle',
    },
    headStyles: {
      fillColor: COLORS.green,
      textColor: COLORS.white,
      fontStyle: 'bold',
      lineColor: COLORS.green,
    },
    alternateRowStyles: { fillColor: [248, 250, 247] },
    columnStyles: Object.fromEntries(numericColumns.map((column) => [column, { halign: 'right' }])),
    rowPageBreak: 'avoid',
  });
  return doc.lastAutoTable.finalY + 6;
}

function addInningsTotal(doc, innings, y) {
  y = addTable(doc, {
    title: 'Innings total',
    headers: ['Team', 'Runs / wickets', 'Overs', 'Run rate'],
    rows: [[innings.team, innings.score, innings.overs, innings.runRate]],
    y,
    numericColumns: [1, 2, 3],
  });
  return addTable(doc, {
    title: 'Extras',
    headers: ['Total', 'Wides', 'No-balls', 'Byes', 'Leg-byes'],
    rows: [
      [
        innings.extras.total,
        innings.extras.wide,
        innings.extras.noBall,
        innings.extras.bye,
        innings.extras.legBye,
      ],
    ],
    y,
    numericColumns: [0, 1, 2, 3, 4],
  });
}

function addFallOfWickets(doc, innings, y) {
  return addTable(doc, {
    title: 'Fall of wickets',
    headers: ['Wkt', 'Score', 'Batter', 'Overs'],
    rows: innings.falls.map((fall) => [fall.wicket, fall.score, fall.batter, fall.overs]),
    y,
    numericColumns: [0, 1, 3],
  });
}

export function createScorecardPdf(match, states) {
  const report = buildScorecard(match, states);
  const doc = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  doc.setProperties({
    title: `${report.title} · Crease scorecard`,
    subject: 'Cricket match scorecard',
    creator: 'Crease',
  });

  writeHeader(doc, report.format);
  doc.setTextColor(...COLORS.deep);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(14);
  doc.text(report.title, PAGE.margin, 37);
  doc.setFont('helvetica', 'normal');
  doc.setTextColor(...COLORS.muted);
  doc.setFontSize(8);
  doc.text(
    [report.date, report.venue].filter(Boolean).join('  ·  ') || 'Match details not recorded',
    PAGE.margin,
    42,
  );

  const first = report.innings[0];
  const second = report.innings[1];
  const cardY = 48;
  const cardWidth = (PAGE.width - PAGE.margin * 2 - 5) / 2;
  [first, second].forEach((innings, index) => {
    const x = PAGE.margin + index * (cardWidth + 5);
    doc.setFillColor(...COLORS.pale);
    doc.roundedRect(x, cardY, cardWidth, 25, 2, 2, 'F');
    doc.setTextColor(...COLORS.muted);
    doc.setFont('helvetica', 'bold');
    doc.setFontSize(8);
    doc.text(innings.team, x + 4, cardY + 7);
    doc.setTextColor(...COLORS.deep);
    doc.setFontSize(16);
    doc.text(innings.score, x + 4, cardY + 16);
    doc.setTextColor(...COLORS.muted);
    doc.setFont('helvetica', 'normal');
    doc.setFontSize(7.5);
    doc.text(`${innings.overs} overs`, x + cardWidth - 4, cardY + 16, { align: 'right' });
  });
  doc.setFillColor(...COLORS.green);
  doc.roundedRect(PAGE.margin, 77, PAGE.width - PAGE.margin * 2, 15, 2, 2, 'F');
  doc.setTextColor(...COLORS.white);
  doc.setFont('helvetica', 'bold');
  doc.setFontSize(10);
  doc.text(report.result, PAGE.width / 2, 86.5, { align: 'center' });
  if (report.playerOfTheMatch) {
    doc.setTextColor(...COLORS.deep);
    doc.setFontSize(8);
    doc.text(`Player of the Match: ${report.playerOfTheMatch}`, PAGE.margin, 98);
  }

  let y = addSectionTitle(doc, `${first.team} · First innings batting`, 101);
  y = addTable(doc, {
    title: '',
    headers: ['Player', 'Dismissal', 'R', 'B', '4s', '6s', 'SR'],
    rows: first.batters.map((player) => [
      player.name,
      player.dismissal,
      player.runs,
      player.balls,
      player.fours,
      player.sixes,
      player.strikeRate,
    ]),
    y: y - 3,
    numericColumns: [2, 3, 4, 5, 6],
  });
  y = addInningsTotal(doc, first, y);
  addFallOfWickets(doc, first, y);

  doc.addPage();
  writeHeader(doc, report.format);
  let pageY = addSectionTitle(doc, `${first.opponent} · First innings bowling`, 37);
  pageY = addTable(doc, {
    title: '',
    headers: ['Bowler', 'O', 'M', 'R', 'W', 'Econ'],
    rows: first.bowlers.map((player) => [
      player.name,
      player.overs,
      player.maidens,
      player.runs,
      player.wickets,
      player.economy,
    ]),
    y: pageY - 3,
    numericColumns: [1, 2, 3, 4, 5],
  });

  pageY = addTable(doc, {
    title: `${second.team} · Second innings batting`,
    headers: ['Player', 'Dismissal', 'R', 'B', '4s', '6s', 'SR'],
    rows: second.batters.map((player) => [
      player.name,
      player.dismissal,
      player.runs,
      player.balls,
      player.fours,
      player.sixes,
      player.strikeRate,
    ]),
    y: pageY,
    numericColumns: [2, 3, 4, 5, 6],
  });
  pageY = addInningsTotal(doc, second, pageY);
  pageY = addFallOfWickets(doc, second, pageY);
  addTable(doc, {
    title: `${second.opponent} · Second innings bowling`,
    headers: ['Bowler', 'O', 'M', 'R', 'W', 'Econ'],
    rows: second.bowlers.map((player) => [
      player.name,
      player.overs,
      player.maidens,
      player.runs,
      player.wickets,
      player.economy,
    ]),
    y: pageY,
    numericColumns: [1, 2, 3, 4, 5],
  });

  writeFooter(doc, report);
  return doc;
}

export function downloadScorecardPdf(match, states) {
  const doc = createScorecardPdf(match, states);
  doc.save(scorecardFilename(match));
}

export async function shareScorecardPdf(match, states) {
  const doc = createScorecardPdf(match, states);
  const file = new File([doc.output('blob')], scorecardFilename(match), {
    type: 'application/pdf',
  });
  if (!navigator.share || !navigator.canShare?.({ files: [file] })) {
    throw new Error('Sharing PDF files is not supported by this browser.');
  }
  await navigator.share({ files: [file], title: 'Crease match scorecard' });
}
